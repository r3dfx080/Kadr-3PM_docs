"""Hybrid ingest (spec §1.2, §3): Haiku reads every sheet, a risk score picks sheets for an Opus re-read,
the best version is promoted to <book>/pages/. Runs in small batches and is resumable at any point.

Usage:
  python -I -X utf8 kb/tools/ingest.py <book slug> [--batch 15] [--jobs 4]   # next batch of that book
  python -I -X utf8 kb/tools/ingest.py --status                              # only rewrite kb/INGEST_STATUS.md

Per book: ocr/haiku/ and ocr/opus/ hold engine output (+ _raw/ replies); a sheet is done when its page in
pages/ carries the "hybrid ingest" marker. Haiku's uncertain readings stay in the promoted page's
`uncertain:` list even after an Opus re-read; only a human removes them. Blank manifest `kind` cells are
filled from the model's KIND. State is derived from files on disk, so kb/INGEST_STATUS.md is always
regenerated, never edited by hand.
"""
import argparse, csv, os, sys

sys.path.insert(0, os.path.dirname(__file__))
from ocr_batch import load, ocr, read_raw, write_page

KB = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
STATUS = os.path.join(KB, "INGEST_STATUS.md")
MARKER = "hybrid ingest"
KINDS = ("title", "toc", "text", "table", "figure", "diagram", "changelog", "insert")
KIND_WEIGHT = {"changelog": 5, "table": 2, "diagram": 2}
RESCAN_AT = 6                                   # score >= this -> Opus re-reads the sheet


def score(fields, manifest_kind):
    """Spec risk score without the Tesseract term: 3*illegible + 2*uncertain + handwritten + kind weight.
    Title-block and signature doubts («штамп: …», «подпись: …») are kept for the proofreader but not scored:
    nearly every sheet has one."""
    kind, _, _, _, uncertain, body = fields
    doubts = [x for x in uncertain if "штамп:" not in x and "подпись:" not in x]   # Haiku may put the tag last
    return (3 * body.count("[неразборчиво]") + 2 * len(doubts) + body.count("<!-- изм")
            + KIND_WEIGHT.get(manifest_kind or kind, 0))


def sheet_state(book, row, stem):
    """-> dict(haiku, score, opus, page) read from disk."""
    d = os.path.join(KB, book)
    st = {"haiku": "-", "score": "", "opus": "-", "page": "-"}
    for eng in ("haiku", "opus"):
        if os.path.exists(os.path.join(d, "ocr", eng, stem + ".md")):
            st[eng] = "ok"
        elif os.path.exists(os.path.join(d, "ocr", eng, stem + ".md.failed.txt")):
            st[eng] = "FAILED"
    h = read_raw(os.path.join(d, "ocr", "haiku"), stem)
    if h:
        st["score"] = score(h[1], row["kind"])
        if st["score"] >= RESCAN_AT and st["opus"] == "-":
            st["opus"] = "needed"
    page = os.path.join(d, "pages", stem + ".md")
    if os.path.exists(page) and MARKER in open(page, encoding="utf-8").read():
        st["page"] = "done"
    return st


def promote(book, row, stem, meta):
    """Write pages/<stem>.md from Opus (if re-read) else Haiku; False if the sheet is not ready."""
    d = os.path.join(KB, book)
    h = read_raw(os.path.join(d, "ocr", "haiku"), stem)
    if not h:
        return False
    s = score(h[1], row["kind"])
    o = read_raw(os.path.join(d, "ocr", "opus"), stem) if s >= RESCAN_AT else None
    if s >= RESCAN_AT and not o:
        return False
    model, fields = o or h
    kind, section, rev, marks, uncertain, body = fields
    if o:                                       # keep Haiku's doubts next to Opus's own
        uncertain = [f"haiku: {x}" for x in h[1][4]] + [f"opus: {x}" for x in uncertain]
    how = f"haiku score {s}" + (f", re-read by {model}" if o else "")
    note = f"{model} via claude -p; {MARKER} ({how}); normalized; not proofread"
    write_page(os.path.join(d, "pages", stem + ".md"), row, meta, model,
               kind, section, rev, marks, uncertain, body, ocr_note=note)
    return True


def fill_kinds(book, rows):
    """Fill blank manifest `kind` cells from the model's KIND reply (SCHEME: classified during the OCR run)."""
    d = os.path.join(KB, book)
    changed = False
    for row, stem in rows:
        if row["kind"]:
            continue
        got = read_raw(os.path.join(d, "ocr", "opus"), stem) or read_raw(os.path.join(d, "ocr", "haiku"), stem)
        if got and got[1][0] in KINDS:
            row["kind"], changed = got[1][0], True
    if changed:
        with open(os.path.join(d, "manifest.csv"), "w", encoding="utf-8", newline="") as f:
            w = csv.DictWriter(f, fieldnames=list(rows[0][0]), lineterminator="\n")
            w.writeheader()
            w.writerows(r for r, _ in rows)


def write_status():
    books = sorted(b for b in os.listdir(KB) if os.path.exists(os.path.join(KB, b, "manifest.csv")))
    head = ["# Ingest status", "",
            "Generated by `kb/tools/ingest.py` from files on disk — do not edit by hand.",
            "To continue, run the next batch of the first book that is not complete:", "",
            "```", "python -I -X utf8 kb/tools/ingest.py <book> --batch 15", "```", "",
            f"Opus re-reads sheets with a Haiku risk score >= {RESCAN_AT}. FAILED = see `<stem>.md.failed.txt`"
            " (often a usage limit; the next run retries it).", "",
            "| Book | Sheets | Pages done | Haiku ok | Opus ok | Opus pending | Failed |", "|---|---|---|---|---|---|---|"]
    tables = []
    for b in books:
        _, rows = load(os.path.join(KB, b))
        sts = [(s, sheet_state(b, r, s)) for r, s in rows]
        n = lambda k, v: sum(st[k] == v for _, st in sts)
        failed = sum("FAILED" in (st["haiku"], st["opus"]) for _, st in sts)
        head.append(f"| {b} | {len(sts)} | {n('page', 'done')} | {n('haiku', 'ok')} | {n('opus', 'ok')} "
                    f"| {n('opus', 'needed')} | {failed} |")
        tables += ["", f"## {b}", "", "| Stem | Haiku | Score | Opus | Page |", "|---|---|---|---|---|"]
        tables += [f"| {s} | {st['haiku']} | {st['score']} | {st['opus']} | {st['page']} |" for s, st in sts]
    open(STATUS, "w", encoding="utf-8").write("\n".join(head + tables) + "\n")


def run_batch(book, size, jobs):
    meta, rows = load(os.path.join(KB, book))
    todo = [(r, s) for r, s in rows if sheet_state(book, r, s)["page"] != "done"][:size]
    if not todo:
        print(f"{book}: все листы готовы")
        return
    want = [s for _, s in todo]
    print(f"{book}: партия {want[0]}…{want[-1]} ({len(want)})", flush=True)
    for stem, status in ocr(os.path.join(KB, book), os.path.join(KB, book, "ocr", "haiku"), "haiku", want, jobs):
        print("haiku", stem, status, flush=True)
    risky = [s for r, s in todo if sheet_state(book, r, s)["opus"] in ("needed", "FAILED")]
    if risky:
        for stem, status in ocr(os.path.join(KB, book), os.path.join(KB, book, "ocr", "opus"), "opus", risky, jobs):
            print("opus ", stem, status, flush=True)
    done = [s for r, s in todo if promote(book, r, s, meta)]
    fill_kinds(book, rows)
    print(f"{book}: в pages/ записано {len(done)} из {len(want)}", flush=True)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("book", nargs="?"); ap.add_argument("--batch", type=int, default=15)
    ap.add_argument("--jobs", type=int, default=4); ap.add_argument("--status", action="store_true")
    args = ap.parse_args()
    if args.book and not args.status:
        run_batch(args.book, args.batch, args.jobs)
    write_status()


if __name__ == "__main__":
    f = ("text", "", "", [], ["27 — blur"], "a [неразборчиво] b <!-- изм. 3: было «x» -->")
    assert score(f, "") == 3 + 2 + 1 and score(f, "changelog") == 11
    assert score(f[:4] + (["штамп: 56 — неясно"],) + f[5:], "") == 3 + 1
    main()
